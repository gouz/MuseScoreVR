// 'fr-CA' -> 'fr'; anything unknown -> 'en'
export function lang(locale) {
  const l = String(locale || '').slice(0, 2).toLowerCase();
  return STRINGS[l] ? l : 'en';
}
export function t(locale, key, ...args) {
  const s = STRINGS[lang(locale)][key] ?? STRINGS.en[key] ?? key;
  return typeof s === 'function' ? s(...args) : s;
}
